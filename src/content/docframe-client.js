// Content-script side of the document frame: injects the hidden iframe once
// and sends files to it (ArrayBuffer transferred, not copied).

const SOURCE = "llm-redactor-docframe";
const TIMEOUT_MS = 60_000;
const READY_AFTER_LOAD_MS = 5_000;
const log = (...args) => console.debug("[llm-redactor docframe]", ...args);

let framePromise = null;
let currentFrame = null;
const pending = new Map();
const progressHandlers = new Map();

// Pages may remove nodes they don't own (e.g. on re-render), so re-create the
// frame whenever the cached one is no longer connected.
async function getFrame() {
  if (currentFrame && !currentFrame.isConnected) {
    log("frame was removed from the page; re-creating");
    framePromise = null;
    currentFrame = null;
  }
  framePromise ??= createFrame();
  const iframe = await framePromise;
  if (!iframe.isConnected || !iframe.contentWindow) {
    framePromise = null;
    currentFrame = null;
    return getFrame();
  }
  return iframe;
}

function createFrame() {
  const promise = new Promise((resolve, reject) => {
    const iframe = document.createElement("iframe");
    iframe.src = chrome.runtime.getURL("docframe.html");
    iframe.setAttribute("data-llm-redactor", "docframe");
    iframe.style.display = "none";
    currentFrame = iframe;
    const timer = setTimeout(() => reject(new Error("document frame did not load")), TIMEOUT_MS);
    let ready = false;
    iframe.addEventListener("load", () => {
      log("iframe load event");
      setTimeout(() => {
        if (!ready) reject(new Error("document frame loaded but never became ready"));
      }, READY_AFTER_LOAD_MS);
    });
    iframe.addEventListener("error", () => reject(new Error("document frame failed to load")));

    window.addEventListener("message", (event) => {
      const msg = event.data;
      if (!msg || msg.source !== SOURCE) return;
      log("message", msg.type, "sourceMatches:", event.source === iframe.contentWindow, "origin:", event.origin);
      if (event.source !== iframe.contentWindow) return;
      if (msg.type === "trace") {
        log("frame:", msg.step);
      } else if (msg.type === "frame-error") {
        log("frame error:", msg.error);
        if (!ready) reject(new Error(`document frame error: ${msg.error}`));
      } else if (msg.type === "ready") {
        ready = true;
        clearTimeout(timer);
        resolve(iframe);
      } else if (msg.type === "progress") {
        progressHandlers.get(msg.id)?.();
      } else if (msg.type === "result") {
        pending.get(msg.id)?.(msg);
        pending.delete(msg.id);
      }
    });
    (document.body ?? document.documentElement).appendChild(iframe);
  });
  promise.catch(() => {
    framePromise = null;
    currentFrame = null;
  });
  return promise;
}

// → { status: "redacted"|"unsupported"|"no-text", file: File, count, swaps }
export async function redactInFrame(file) {
  const iframe = await getFrame();
  const id = `${Date.now().toString(36)}-${Math.random().toString(36).slice(2)}`;
  const buffer = await file.arrayBuffer();

  const msg = await new Promise((resolve, reject) => {
    // The timeout restarts on every progress message, so large PDFs that are
    // still being processed don't fail open.
    let timer;
    const arm = () => {
      clearTimeout(timer);
      timer = setTimeout(() => {
        pending.delete(id);
        progressHandlers.delete(id);
        reject(new Error("timed out"));
      }, TIMEOUT_MS);
    };
    arm();
    progressHandlers.set(id, arm);
    pending.set(id, (m) => {
      clearTimeout(timer);
      progressHandlers.delete(id);
      resolve(m);
    });
    iframe.contentWindow.postMessage(
      { source: SOURCE, type: "redact", id, name: file.name, mime: file.type, buffer },
      new URL(iframe.src).origin,
      [buffer],
    );
  });

  if (msg.error) throw new Error(msg.error);
  const warnings = msg.warnings ?? [];
  if (msg.status !== "redacted") return { status: msg.status, file, count: 0, swaps: [], warnings };
  const out = new File([msg.buffer], file.name, { type: file.type, lastModified: file.lastModified });
  return { status: "redacted", file: out, count: msg.count, swaps: msg.swaps ?? [], warnings };
}

// Restore stand-ins in a file the site hands back (generated by the model).
// → Uint8Array of restored bytes, or null when there was nothing to restore.
export async function restoreInFrame({ name, mime, buffer }) {
  const iframe = await getFrame();
  const id = `${Date.now().toString(36)}-${Math.random().toString(36).slice(2)}`;
  const msg = await new Promise((resolve, reject) => {
    let timer;
    const arm = () => {
      clearTimeout(timer);
      timer = setTimeout(() => {
        pending.delete(id);
        progressHandlers.delete(id);
        reject(new Error("timed out"));
      }, TIMEOUT_MS);
    };
    arm();
    progressHandlers.set(id, arm);
    pending.set(id, (m) => {
      clearTimeout(timer);
      progressHandlers.delete(id);
      resolve(m);
    });
    iframe.contentWindow.postMessage({ source: SOURCE, type: "restore", id, name, mime, buffer }, new URL(iframe.src).origin, [buffer]);
  });
  if (msg.error) throw new Error(msg.error);
  return msg.status === "redacted" && msg.buffer ? new Uint8Array(msg.buffer) : null;
}
